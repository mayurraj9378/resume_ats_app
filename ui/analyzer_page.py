"""Streamlit page: ATS analyzer."""
import streamlit as st

from modules.ats_analyzer import analyze
from modules.llm_suggestions import GeminiError, get_last_model, review_resume
from modules.parser import extract_text
from ui.settings import get_api_key


def _color(score: int) -> str:
    return "🟢" if score >= 75 else "🟡" if score >= 50 else "🔴"


def render():
    st.header("🎯 ATS Resume Analyzer")
    c1, c2 = st.columns(2, gap="large")

    resume_text = ""
    with c1:
        st.subheader("Resume")
        f = st.file_uploader("Upload PDF, DOCX or TXT", type=["pdf", "docx", "txt"])
        if f:
            try:
                resume_text = extract_text(f)
            except Exception as e:  # noqa: BLE001
                st.error(f"Could not read file: {e}")
        if resume_text:
            with st.expander("Extracted text"):
                st.text(resume_text[:5000])

    with c2:
        st.subheader("Job description (optional but recommended)")
        jd = st.text_area("Paste the job description", height=300, label_visibility="collapsed")

    if st.button("Analyze", type="primary", disabled=not resume_text.strip()):
        st.session_state["analysis"] = {"res": analyze(resume_text, jd), "resume": resume_text, "jd": jd}
        st.session_state.pop("ai_review", None)

    data = st.session_state.get("analysis")
    if not data:
        return
    res, resume_text, jd = data["res"], data["resume"], data["jd"]

    st.divider()
    m1, m2, m3 = st.columns(3)
    m1.metric("ATS score", f"{_color(res.total)} {res.total}/100")
    m2.metric("Words", res.word_count)
    m3.metric("JD similarity", f"{res.similarity:.0%}" if jd.strip() else "—")
    st.progress(res.total / 100)

    st.subheader("Score breakdown")
    cols = st.columns(len(res.breakdown))
    for col, (name, (got, mx)) in zip(cols, res.breakdown.items()):
        col.metric(name, f"{got}/{mx}")

    k1, k2 = st.columns(2)
    with k1:
        st.subheader("✅ Matched" if jd.strip() else "✅ Skills detected")
        st.write(", ".join(f"`{k}`" for k in res.matched) or "None found")
    with k2:
        if jd.strip():
            st.subheader("❌ Missing keywords")
            st.write(", ".join(f"`{k}`" for k in res.missing) or "None 🎉")
        else:
            st.subheader("Sections")
            st.write("Found: " + (", ".join(res.sections_found) or "none"))
            if res.sections_missing:
                st.write("Missing: " + ", ".join(res.sections_missing))

    st.subheader("💡 Suggestions")
    for s in res.suggestions:
        st.write(f"• {s}")

    st.divider()
    st.subheader("✨ AI review (Gemini)")
    key = get_api_key()
    if not key:
        st.info("Add your Gemini API key in the sidebar to get rewritten bullets and tailored advice.")
    elif st.button("Generate AI review"):
        with st.spinner("Asking Gemini..."):
            try:
                st.session_state["ai_review"] = review_resume(key, resume_text, jd, res.missing)
                st.session_state["ai_model"] = get_last_model()
            except GeminiError as e:
                st.error(str(e))
    if st.session_state.get("ai_review"):
        st.caption(f"Generated by `{st.session_state.get('ai_model', 'gemini')}`")
        st.markdown(st.session_state["ai_review"])
